import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const contractPath = path.join(root, "contracts", "command_contract.json");
const schemaPath = path.join(root, "contracts", "protocol.schema.json");
const generatedCommandsPath = path.join(
  root,
  "ui",
  "src",
  "lib",
  "protocol-commands.generated.ts",
);
const generatedErrorCodesPath = path.join(
  root,
  "ui",
  "src",
  "lib",
  "error-codes.generated.ts",
);
const generatedInvalidDir = path.join(root, "fixtures", "protocol", "invalid");
const generatedInvalidManifestPath = path.join(
  root,
  "fixtures",
  "protocol",
  "generated-invalid-manifest.json",
);
const contract = JSON.parse(readFileSync(contractPath, "utf8"));

const outputs = new Map([
  [schemaPath, generateProtocolSchema()],
  [generatedCommandsPath, generateTypeScriptCommands()],
  [generatedErrorCodesPath, generateTypeScriptErrorCodes()],
]);
for (const [name, content] of generateInvalidFixtures()) {
  outputs.set(path.join(generatedInvalidDir, name), content);
}

const stale = [];
for (const [file, expected] of outputs) {
  const actual = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (actual !== expected) stale.push(path.relative(root, file));
}
if (existsSync(generatedInvalidDir)) {
  for (const entry of readdirSync(generatedInvalidDir, { withFileTypes: true })) {
    const file = path.join(generatedInvalidDir, entry.name);
    if (
      entry.isFile() &&
      entry.name.startsWith("generated_") &&
      entry.name.endsWith(".json") &&
      !outputs.has(file)
    ) {
      stale.push(path.relative(root, file));
      if (!check) unlinkSync(file);
    }
  }
}

if (check) {
  if (stale.length) {
    console.error(`Generated protocol artifacts are stale:\n${[...new Set(stale)].join("\n")}`);
    process.exitCode = 1;
  }
} else {
  for (const [file, expected] of outputs) {
    mkdirSync(path.dirname(file), { recursive: true });
    if (!existsSync(file) || readFileSync(file, "utf8") !== expected) {
      writeFileSync(file, expected, "utf8");
    }
  }
  console.log(`Generated ${outputs.size} protocol artifacts from ${path.relative(root, contractPath)}.`);
}

function generateProtocolSchema() {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  schema.description =
    "Generated control-plane sections come from command_contract.json; snapshot/status definitions remain maintained here.";
  schema.$defs ??= {};
  for (const [name, definition] of Object.entries(contract.definitions)) {
    if (definition.tsType) continue;
    schema.$defs[name] = toJsonSchema(definition);
  }
  schema.$defs.errorCode = { enum: contract.errorCodes.map(({ code }) => code) };
  schema.$defs.command = {
    oneOf: contract.commands.map((command) => ({
      type: "object",
      required: ["protocolVersion", "id", "kind", "payload"],
      properties: {
        protocolVersion: { const: contract.protocolVersion },
        id: { $ref: "#/$defs/u64" },
        kind: { const: command.kind },
        payload: toJsonSchema(command.payload),
      },
    })),
  };
  schema.$defs.event = {
    oneOf: contract.events.map((event) => ({
      type: "object",
      required: ["kind", "payload"],
      properties: {
        kind: { const: event.kind },
        payload: toJsonSchema(event.payload),
      },
    })),
  };
  return `${JSON.stringify(schema, null, 2)}\n`;
}

function toJsonSchema(value) {
  if (Array.isArray(value)) return value.map(toJsonSchema);
  if (!value || typeof value !== "object") return value;
  const result = {};
  for (const [key, child] of Object.entries(value)) {
    if (key === "tsType") continue;
    result[key] =
      key === "$ref"
        ? child.replace("#/definitions/", "#/$defs/")
        : toJsonSchema(child);
  }
  return result;
}

function generateTypeScriptCommands() {
  const imports = new Set();
  const payloadLines = [];
  const resultLines = [];
  const errorLines = [];
  const emptyKinds = [];
  for (const command of contract.commands) {
    payloadLines.push(
      `  ${JSON.stringify(command.kind)}: ${schemaToTypeScript(command.payload, imports)};`,
    );
    resultLines.push(
      `  ${JSON.stringify(command.kind)}: ${schemaToTypeScript(command.result, imports)};`,
    );
    errorLines.push(
      `  ${JSON.stringify(command.kind)}: ${command.errors.length ? command.errors.map(JSON.stringify).join(" | ") : "never"};`,
    );
    if (isEmptyObject(command.payload)) emptyKinds.push(JSON.stringify(command.kind));
  }
  const importLine = imports.size
    ? `import type { ${[...imports].sort().join(", ")} } from "./types";\n`
    : "";
  return `// Generated by scripts/generate-protocol-artifacts.mjs. Do not edit.\n` +
    `import { invoke } from "@tauri-apps/api/core";\n` +
    importLine +
    `\nexport type CommandKind = ${contract.commands.map(({ kind }) => JSON.stringify(kind)).join(" | ")};\n` +
    `export type ErrorCode = ${contract.errorCodes.map(({ code }) => JSON.stringify(code)).join(" | ")};\n` +
    `type EmptyCommandKind = ${emptyKinds.join(" | ")};\n\n` +
    `/** bridge rejection 的結構化形狀(code = engine 錯誤碼或 not_connected/disconnected/timeout) */\n` +
    `export interface CommandError {\n  code: string;\n  message: string;\n}\n\n` +
    `export function toCommandError(raw: unknown): CommandError {\n` +
    `  if (typeof raw === "object" && raw !== null &&\n` +
    `      typeof (raw as CommandError).code === "string" &&\n` +
    `      typeof (raw as CommandError).message === "string")\n` +
    `    return raw as CommandError;\n` +
    `  return { code: "internal", message: raw instanceof Error ? raw.message : String(raw) };\n` +
    `}\n\n` +
    `export interface CommandPayloads {\n${payloadLines.join("\n")}\n}\n\n` +
    `export interface CommandResults {\n${resultLines.join("\n")}\n}\n\n` +
    `export interface CommandErrors {\n${errorLines.join("\n")}\n}\n\n` +
    `export function engineCommand<K extends CommandKind>(\n` +
    `  kind: K,\n` +
    `  ...args: K extends EmptyCommandKind\n` +
    `    ? [payload?: CommandPayloads[K]]\n` +
    `    : [payload: CommandPayloads[K]]\n` +
    `): Promise<CommandResults[K]> {\n` +
    `  return invoke<CommandResults[K]>("engine_command", { kind, payload: args[0] ?? {} }).catch(\n` +
    `    (raw: unknown) => {\n` +
    `      throw toCommandError(raw);\n` +
    `    },\n` +
    `  );\n` +
    `}\n`;
}

function generateTypeScriptErrorCodes() {
  const codes = contract.errorCodes.map(({ code }) => JSON.stringify(code));
  return `// Generated by scripts/generate-protocol-artifacts.mjs. Do not edit.\n` +
    `export const ERROR_CODES = [${codes.join(", ")}] as const;\n` +
    `export type ErrorCode = (typeof ERROR_CODES)[number];\n`;
}

function schemaToTypeScript(schema, imports) {
  const resolved = resolve(schema);
  if (resolved.tsType) {
    imports.add(resolved.tsType);
    return resolved.tsType;
  }
  if (resolved.oneOf) {
    return resolved.oneOf.map((candidate) => schemaToTypeScript(candidate, imports)).join(" | ");
  }
  if (resolved.const !== undefined) return JSON.stringify(resolved.const);
  if (resolved.enum) return resolved.enum.map((value) => JSON.stringify(value)).join(" | ");
  switch (resolved.type) {
    case "string":
      return "string";
    case "boolean":
      return "boolean";
    case "integer":
    case "number":
      return "number";
    case "null":
      return "null";
    case "array":
      return `Array<${schemaToTypeScript(resolved.items ?? {}, imports)}>`;
    case "object": {
      const properties = resolved.properties ?? {};
      if (Object.keys(properties).length === 0) {
        return resolved.maxProperties === 0
          ? "Record<string, never>"
          : "Record<string, unknown>";
      }
      const required = new Set(resolved.required ?? []);
      return `{ ${Object.entries(properties)
        .map(
          ([key, child]) =>
            `${JSON.stringify(key)}${required.has(key) ? "" : "?"}: ${schemaToTypeScript(child, imports)}`,
        )
        .join("; ")} }`;
    }
    default:
      return "unknown";
  }
}

function isEmptyObject(schema) {
  const resolved = resolve(schema);
  return resolved.type === "object" && resolved.maxProperties === 0;
}

function generateInvalidFixtures() {
  const files = new Map();
  const manifest = { schemaVersion: 1, commands: {} };
  let id = 100000;
  for (const command of contract.commands) {
    const payloadSchema = resolve(command.payload);
    const properties = payloadSchema.properties ?? {};
    const required = new Set(payloadSchema.required ?? []);
    const base = sampleFor(payloadSchema);
    const coverage = { missing: [], wrongType: [] };
    for (const field of required) {
      const payload = structuredClone(base);
      delete payload[field];
      const name = `generated_command_${snake(command.kind)}_missing_${snake(field)}.json`;
      files.set(name, fixture(command.kind, payload, id++));
      coverage.missing.push(field);
    }
    for (const [field, fieldSchema] of Object.entries(properties)) {
      const payload = structuredClone(base);
      payload[field] = wrongFor(fieldSchema);
      const name = `generated_command_${snake(command.kind)}_bad_${snake(field)}_type.json`;
      files.set(name, fixture(command.kind, payload, id++));
      coverage.wrongType.push(field);
    }
    manifest.commands[command.kind] = coverage;
  }
  outputs.set(generatedInvalidManifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  return files;
}

function fixture(kind, payload, id) {
  return `${JSON.stringify({ protocolVersion: contract.protocolVersion, id, kind, payload })}\n`;
}

function sampleFor(schema) {
  const resolved = resolve(schema);
  if (resolved.oneOf) return sampleFor(resolved.oneOf[0]);
  if (resolved.const !== undefined) return structuredClone(resolved.const);
  if (resolved.enum) return structuredClone(resolved.enum[0]);
  switch (resolved.type) {
    case "string":
      return "fixture";
    case "boolean":
      return true;
    case "integer":
      return Math.max(0, resolved.minimum ?? 0);
    case "number":
      return resolved.minimum ?? 0.5;
    case "null":
      return null;
    case "array":
      return [];
    case "object": {
      const object = {};
      for (const field of resolved.required ?? []) {
        object[field] = sampleFor(resolved.properties[field]);
      }
      return object;
    }
    default:
      return null;
  }
}

function wrongFor(schema) {
  const resolved = resolve(schema);
  if (resolved.oneOf) return false;
  if (resolved.const !== undefined || resolved.enum) return null;
  switch (resolved.type) {
    case "string":
    case "integer":
    case "number":
      return false;
    case "boolean":
      return "not-a-boolean";
    case "null":
      return false;
    case "array":
      return {};
    case "object":
      return [];
    default:
      return false;
  }
}

function resolve(schema) {
  if (!schema.$ref) return schema;
  const name = schema.$ref.replace("#/definitions/", "");
  const definition = contract.definitions[name];
  if (!definition) throw new Error(`Unknown contract definition: ${schema.$ref}`);
  return resolve(definition);
}

function snake(value) {
  return value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/[^a-zA-Z0-9]+/g, "_").toLowerCase();
}
